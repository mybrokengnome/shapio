import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { createClient, SCHEMA_VERSION_QUERY_PARAMETER, ShapioApiError } from '@shapio/client';
import type { CliCommand } from '../../types.js';

const DEFAULT_URL = 'http://localhost:4300';
const DEFAULT_OUT = 'shapio-types.ts';

type TypesResponse = { schemaVersion: number; source: string };

/**
 * The `SCHEMA_VERSION` the server writes into the source (server 0.9.0 or later):
 * `export const SCHEMA_VERSION = '<schemaId>:<version>' as const;`. Undefined for an older server's source.
 */
export const schemaVersionTokenOf = (source: string): string | undefined =>
  /^export const SCHEMA_VERSION = '([^']+)'/m.exec(source)?.[1];

/** A declaration file (`.d.ts`, `.d.mts`, `.d.cts`): it may declare the constant but not initialize it. */
const DECLARATION_FILE = /\.d\.[cm]?ts$/;

/**
 * The source as a declaration file holds it: `export declare const SCHEMA_VERSION: '<schemaId>:<version>';`
 * instead of the module's `as const` initializer, which `tsc` refuses in a `.d.ts`. Everything else is types.
 */
export const asDeclarationFile = (source: string): string =>
  source.replace(
    /^export const SCHEMA_VERSION = ('[^'\n]+') as const;$/m,
    'export declare const SCHEMA_VERSION: $1;',
  );

/** The types path: today's schema, or the version `--schema-version` names. */
const typesPath = (schemaVersion: string | undefined) =>
  schemaVersion === undefined
    ? '/api/docs/typescript'
    : `/api/docs/typescript?${SCHEMA_VERSION_QUERY_PARAMETER}=${encodeURIComponent(schemaVersion)}`;

/**
 * `shapio types generate`: writes TypeScript declarations for the instance's active schema into the
 * consuming project, as the server renders them (the file is written as received; the server's source starts
 * with the "Generated by" and schema version comments). From server 0.9.0 the source exports `SCHEMA_VERSION`,
 * the schema version a client passes as `schemaVersion` to keep reading in this shape;
 * `--schema-version <schemaId>:<version>` renders the types of an older schema version instead. Over HTTP with
 * an admin API token, like the schema commands (never direct DB access).
 */
export const typesGenerateCommand: CliCommand = {
  summary: 'Write TypeScript types for the instance’s models and components',
  usage:
    'shapio types generate [--url <origin>] [--token <admin token>] [--out shapio-types.ts] [--schema-version <schemaId>:<version>]',
  run: async (args, io) => {
    const { values } = parseArgs({
      args: [...args],
      options: {
        url: { type: 'string' },
        token: { type: 'string' },
        out: { type: 'string' },
        'schema-version': { type: 'string' },
      },
      allowPositionals: false,
    });
    const token = values.token ?? io.env.SHAPIO_TOKEN;
    if (!token) {
      io.stderr('shapio types generate: an admin API token is required: pass --token or set SHAPIO_TOKEN\n');
      return 1;
    }
    const baseUrl = values.url ?? io.env.SHAPIO_URL ?? DEFAULT_URL;
    const out = resolve(values.out ?? DEFAULT_OUT);
    const requested = values['schema-version'];
    if (requested !== undefined && requested.trim() === '') {
      io.stderr(
        'shapio types generate: --schema-version needs a schema version, such as the SCHEMA_VERSION of an older types file\n',
      );
      return 1;
    }
    try {
      const { schemaVersion, source } = await createClient({ baseUrl, token }).request<TypesResponse>(
        typesPath(requested),
      );
      await mkdir(dirname(out), { recursive: true });
      await writeFile(out, DECLARATION_FILE.test(out) ? asDeclarationFile(source) : source, 'utf8');
      const written = schemaVersionTokenOf(source);
      const versionNote = written === undefined ? '' : ` (SCHEMA_VERSION ${written})`;
      io.stdout(
        `Wrote types for schema version ${schemaVersion}${versionNote} to ${relative(process.cwd(), out) || out}\n`,
      );
      if (written === undefined) {
        io.stdout(
          'The server sent no SCHEMA_VERSION (Shapio before 0.9.0): clients built on these types read today’s schema.\n',
        );
      }
      return 0;
    } catch (error) {
      if (error instanceof ShapioApiError) {
        io.stderr(`shapio types generate: ${error.code}: ${error.message}\n`);
        return 1;
      }
      throw error;
    }
  },
};
